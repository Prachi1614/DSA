public class BinaryNumberSystem {
    public static void main(String[] args) {
        /*Binary AND &
          Binary OR |
          Binary XOR ^
          Bianry one's Compliment ~
          Binary left Shift <<
          Binary Right Shift >> */

        // Binary AND &
        System.out.println(5 & 6);

        //Binary OR |
        System.out.println(5 | 6);

        //Binary XOR ^
        System.out.println(5 ^ 6);

        //1'S compliment ~
        System.out.println(~4);

        //Left shift operator <<
        System.out.println(5<<2);

        //Right shift >>
        System.out.println(6>>1);
    }
}
